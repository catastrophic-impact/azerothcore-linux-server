-- Regenerates addons/wotlk_pets/PetDex.lua: every wild-obtainable species (id -> name, family, icon) so the journal can list pets you have NOT collected yet.
-- luajit pet-battle/gen_pet_dex.lua   (project root, HOST). Run after adding zones / species; gen_zone_levels.py makes the matching "where to find" data.
package.path = "scripts/?.lua;" .. package.path
local D = require("pb_data"); local C = require("pb_core")
local ids = {}; for e, sp in pairs(D.species) do if sp.wild or sp.companion then ids[#ids + 1] = e end end; table.sort(ids)
local out = { "-- Generated by pet-battle/gen_pet_dex.lua. Do not edit.\nWotlkPetDex = {" }
for _, id in ipairs(ids) do
    local sp = D.species[id]
    out[#out + 1] = string.format('    [%d] = { %q, %q, %q },', id, sp.name, C.Family(id), sp.icon or "INV_Misc_QuestionMark")
end
out[#out + 1] = "}\n"
local f = assert(io.open("addons/wotlk_pets/PetDex.lua", "w")); f:write(table.concat(out, "\n")); f:close()
print(#ids .. " species")
