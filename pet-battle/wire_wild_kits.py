#!/usr/bin/env python3 -I
"""Wire the Outland/Northrend zones into the pet-battle data (idempotent; run from the repo root, then the generators it prints):
  1. zone_ranges.tsv rows (status 'composed', source = Petopia forum t=19184, the same source as the shipped zones) + pet-battle/<zone>_roster.tsv for each zone (include=Y rows = the kinds in zone_census.tsv)
  2. zone ids into the ZONES set of scripts/pb_wild.lua
  3. the one-line hook in scripts/pb_data.lua that loads scripts/pb_wild_kits.lua (generated by gen_wild_kits.py)
minMob/maxMob = spawn-weighted 3rd..97th percentile of the zone's non-critter mid levels (stray low-level kinds and critters would stretch the pet-level curve)."""
import re, collections
SRC = 'Petopia forum t=19184'
Z = [  # slug, zoneId, map, pet lo, pet hi, name
 ('hellfire', 3483, 530, 17, 18, 'Hellfire Peninsula'), ('zangarmarsh', 3521, 530, 18, 18, 'Zangarmarsh'), ('terokkar', 3519, 530, 18, 18, 'Terokkar Forest'), ('nagrand', 3518, 530, 18, 18, 'Nagrand'),
 ('bladesedge', 3522, 530, 18, 19, "Blade's Edge Mountains"), ('netherstorm', 3523, 530, 20, 20, 'Netherstorm'), ('shadowmoon', 3520, 530, 20, 20, 'Shadowmoon Valley'),
 ('borean', 3537, 571, 20, 21, 'Borean Tundra'), ('howlingfjord', 495, 571, 20, 21, 'Howling Fjord'), ('dragonblight', 65, 571, 22, 22, 'Dragonblight'), ('grizzly', 394, 571, 21, 21, 'Grizzly Hills'),
 ('zuldrak', 66, 571, 22, 22, "Zul'Drak"), ('sholazar', 3711, 571, 21, 21, 'Sholazar Basin'), ('stormpeaks', 67, 571, 22, 22, 'The Storm Peaks'), ('icecrown', 210, 571, 22, 22, 'Icecrown'),
 ('crystalsong', 2817, 571, 22, 22, 'Crystalsong Forest'), ('wintergrasp', 4197, 571, 22, 22, 'Wintergrasp')]
TYPE = {'1': 'Beast', '2': 'Dragonkin', '3': 'Demon', '4': 'Elemental', '5': 'Giant', '6': 'Undead', '7': 'Humanoid', '8': 'Critter', '9': 'Mechanical'}
fam = {}   # entry -> assigned pet family (family_rules.py); kinds it dropped as junk are not rostered
for l in list(open('pet-battle/family_assign.tsv'))[1:]:
    x = l.rstrip('\n').split('\t'); fam[x[1]] = x[5]
by = collections.defaultdict(list)
for l in open('pet-battle/zone_census.tsv'):
    x = l.rstrip('\n').split('\t')
    if x[1] in fam: by[x[0]].append(x)
def wpct(ks, p):   # spawn-weighted percentile of the kinds' mid level
    v = sorted((((int(k[6]) + int(k[7])) / 2), int(k[8])) for k in ks); tot = sum(w for _, w in v); acc = 0
    for lv, w in v:
        acc += w
        if acc >= tot * p: return int(round(lv))
    return int(round(v[-1][0]))
rows = open('pet-battle/zone_ranges.tsv', encoding='utf-8').read()
new = []
print('%-24s %5s %5s %4s-%-4s %s' % ('zone', 'kinds', 'id', 'lo', 'hi', 'mob range'))
for slug, zid, mp, lo, hi, name in Z:
    ks = by[name]; nc = [k for k in ks if k[3] != '8'] or ks
    mn = wpct(nc, 0.03); mx = wpct(nc, 0.97)
    print('%-24s %5d %5d %4d-%-4d %d-%d' % (name, len(ks), zid, lo, hi, mn, mx))
    out = ['# %s pet roster (composed kits; census = creature kinds with >= 3 spawns whose most spawns sit in the zone box, rank 0, no npcflag/citizen/guard/event names). Same columns as elwynn_roster.tsv.' % name,
           '# archetype is obsolete (composed kits: pet-battle/assemble_kits.py).', 'include\tentry\tname\tlevels\ttype\tfamily\trank\tspawns\tdisplay\tarchetype\tabilities\tnotes']
    for k in sorted(ks, key=lambda k: (int(k[6]), k[2])):
        zn, e, nm, t, cf, rk, lo2, hi2, sp = k
        out.append('\t'.join(['Y', e, nm, lo2 if lo2 == hi2 else '%s-%s' % (lo2, hi2), TYPE.get(t, t), cf, rk, sp, '0', 'Melee', '', 'composed kit: ' + fam[e]]))
    open('pet-battle/%s_roster.tsv' % slug, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    if '\n%s\t' % slug not in '\n' + rows: new.append('\t'.join([slug, str(zid), str(mp), '-', '-', '-', '-', '-', str(lo), str(hi), str(mn), str(mx), name, SRC, 'composed']))
if new: open('pet-battle/zone_ranges.tsv', 'a', encoding='utf-8').write('\n'.join(new) + '\n'); print('zone_ranges.tsv: +%d rows' % len(new))
w = open('scripts/pb_wild.lua').read(); add = [z[1] for z in Z if '[%d] = true' % z[1] not in w.split('\n')[9]]
if add: w = w.replace('local ZONES = { ', 'local ZONES = { ' + ' '.join('[%d] = true,' % z for z in add) + ' ', 1); open('scripts/pb_wild.lua', 'w').write(w); print('pb_wild ZONES +%d' % len(add))
d = open('scripts/pb_data.lua').read()
if 'pb_wild_kits' not in d:
    d = d.replace('\nreturn D\n', '\n-- composed wild-mob kits for the Outland/Northrend zones (GENERATED: pet-battle/gen_wild_kits.py; zones: pet-battle/wire_wild_kits.py)\npackage.loaded["pb_data"] = D   -- the generated file requires pb_data itself\nrequire("pb_wild_kits")\n\nreturn D\n', 1) if d.rstrip().endswith('return D') else d
    open('scripts/pb_data.lua', 'w').write(d); print('pb_data hook added')
print('next: python3 -I pet-battle/assemble_kits.py pet-battle/.s/ability_roles.tsv > pet-battle/kits_prototype.tsv; python3 -I pet-battle/gen_wild_kits.py scripts/pb_wild_kits.lua')
