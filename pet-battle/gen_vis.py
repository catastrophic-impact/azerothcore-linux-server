#!/usr/bin/env python3 -I
"""Builds scripts/pb_vis.lua: the presentation of EVERY retail pet ability (visual spell + how it is played), as DATA.
Order of authority per ability:  lab   = the spell the user ACCEPTED in the ability lab (pet-battle/ability_visuals.tsv + lab data, kept exactly with its mode)
                                 name  = a 3.3.5 player/creature spell with the SAME NAME (instant, no movement effect), user rule 'name first'
                                 rule  = effect kind x range x family -> default spell (table below; theme spells are the projectile spells vetted by check_fx.py)
                                 none  = no spell: the battle keeps its neutral cast glow (weather, pure bookkeeping abilities)
Modes: melee (run up, hit, return) | ranged (stay, spell flies) | self (buff/heal on the pet) | target (debuff spell at the enemy) | aura (AddAura on the pet, no cast animation)
Inputs (host): pet-battle/.s/all.tsv (luajit pet-battle/vis_dump_all.lua) and .s/lab.tsv (luajit pet-battle/vis_dump_lab.lua): both are regenerated by this script's wrapper `sh pet-battle/gen_vis.sh`.
Prints the whole table so a wrong pick is visible.  usage (project root): sh pet-battle/gen_vis.sh"""
import csv, re, struct, sys, collections
csv.field_size_limit(10 ** 9)
S = 'pet-battle/.s/'
def dbc(name):
    d = open('release/data/dbc/%s.dbc' % name, 'rb').read(); _, c, f, rs, ss = struct.unpack('<4sIIII', d[:20])
    recs = [struct.unpack_from('<%dI' % f, d, 20 + i * rs) for i in range(c)]; sb = 20 + c * rs
    return recs, (lambda off: d[sb + off:d.index(b'\0', sb + off)].decode('latin1'))
SP, sps = dbc('Spell'); DUR, _ = dbc('SpellDuration'); DURMS = {r[0]: struct.unpack('<i', struct.pack('<I', r[1]))[0] for r in DUR}
SL, _ = dbc('SkillLineAbility'); SK = {r[2] for r in SL}
JUNK = ('dnd', 'dummy', 'test', 'zzold', 'deprecated', '[ph]', 'unused')
MOVE = {5, 96, 98, 29, 3}   # teleport / charge / leap effects: the caster would fly across the arena
DMG_EFFECTS = (2, 17, 19, 31, 58)
byname = collections.defaultdict(list); DMG = set()
for r in SP:
    n = sps(r[136])
    if any(r[71 + e] in DMG_EFFECTS for e in range(3)): DMG.add(r[0])
    if not (n and r[131]) or any(j in n.lower() for j in JUNK): continue
    aura = any(r[95 + e] for e in range(3)) or DURMS.get(r[40], 0) != 0
    instant = r[28] in (0, 1)
    if aura or not instant or any(r[71 + e] in MOVE for e in range(3)): continue
    byname[n.lower()].append((r[0], r[0] in SK))
def samename(nm):
    L = [t for t in byname.get(nm.lower(), []) if t[1]]   # PLAYER spells only: a creature spell with the same name is unvetted (Consume, Quake, Dive...)
    return sorted(L)[0][0] if L else None
NAMEBAN = {'charge', 'feed', 'focus', 'prowl', 'flash', 'deflection', 'apocalypse', 'soothe', 'light', 'strike', 'crush', 'smash', 'hiss', 'howl', 'screech', 'devastate', 'immolation', 'leap'}   # same name, different meaning (a player/creature spell that does something else)

# ---- rule tables (spell ids all verified in the lab or vetted instant projectile spells)
THEME = [   # same rows as pb_core THEME_VIS: name prefix themes -> projectile spell
 ("frost|ice$|icy|icicle|snow|freez|chill|blizzard|winter|glacial|hail", 116), ("fire|flame|burn|scorch|ember|lava|magma|immolat|inferno|meteor|candle|sear$|searing|cinder|blaz", 9053),
 ("shadow|dark|death|curse|void|drain|nether|nightmare|spectral|soul|ghost|dread|siphon", 686), ("web|ooze|poison|toxic|acid|plague|rot$|rotting|infect|venom|spore|leech|corros|creeping|rust|sap$", 9591),
 ("leaf|thorn|vine|branch|seed|wrath|bloom|ironbark|woodchip|photosyn|bark|root|entangl|ensnar", 5176), ("lightning|thunder|shock|storm|static|zap|spark", 403),
 ("holy|light$|lights|smite|radian|sunlight|sunfire|sunbeam|sun$|solar|beacon", 31759), ("arcane|mana|surge|nova$|beam|power|counterspell|chaos|focused", 7269),
 ("water|wave|spray|tide|tidal|geyser|jet$|brine|mud|rain$|bubble", 31012), ("rock$|rocky|rockfall|stone|boulder|quake|crystal|sand|dust|pebble|earth|avalanche|rockslide", 9483),
 ("wind|gust|tornado|cyclone|whirl|screech|shriek|slicing|squall", 3044)]
def theme(name):
    pad = ' ' + re.sub(r'[^\w\s]', ' ', name.lower()) + ' '
    for pats, sp in THEME:
        for p in pats.split('|'):
            whole = p.endswith('$')
            if (' ' + (p[:-1] + ' ' if whole else p)) in pad: return sp
FAM = {0: 'Humanoid', 1: 'Dragonkin', 2: 'Flying', 3: 'Undead', 4: 'Critter', 5: 'Magic', 6: 'Elemental', 7: 'Beast', 8: 'Aquatic', 9: 'Mechanical'}
RANGED_FAM = {1, 5, 6, 8}
FAM_RANGED = {5: 30451, 6: 9053, 8: 35499, 3: 1120, 2: 64422, 1: 12533}   # Arcane Blast, fire bolt, Water Spout, Drain Soul, Sonic Screech, Acid Breath (all lab-accepted except the fire bolt)
FAM_HEAL = {8: 331, 5: 2054, 4: 596, 7: 596}                                # Healing Wave, Heal, Prayer of Healing (lab-accepted); the rest Rejuvenation 774
BITE = re.compile(r'bite|chomp|fang|devour|gnaw|peck|chew|gobble|nibble|snap')
CLAW = re.compile(r'claw|scratch|rake|swipe|slash|rip$|tear|talon|mangle|pounce|flank|flurry|thrash')
STOMP = re.compile(r'hoof|stomp|trample')
DEF = re.compile(r'shield|ward|block|barrier|plating|armor|protect|fortif|carapace|stone form|hunker|crouch|skin|survival|deflect')
SOUND = re.compile(r'screech|shriek|howl|squawk|trumpet|cry$|call$|bellow')   # sound attacks / debuffs: the lab-accepted Sonic Screech
DEFER = {163, 250, 581, 706}   # Stampede, Spiderling Swarm, Flock, Swarm: summoned-copies choreography (plan 1b), no spell yet: the battle keeps its present behaviour
DODGE = re.compile(r'dodge|evade|evasion|feint|hide|stealth|prowl|vanish|burrow|blink|nocturnal')

def melee_spell(name, fam):
    n = name.lower()
    if BITE.search(n): return 17253
    if CLAW.search(n): return 3009
    if STOMP.search(n): return 20549
    return 78 if fam == 0 else 1766   # Heroic Strike for humanoid weapon blows, Kick (the user's favourite landing) for everything else

def rule(name, fam, dmg, heal, side, rng):
    """returns (spell, mode, dmg flag) from the kind of the ability, or None"""
    if SOUND.search(name.lower()) and (dmg or side == 'enemy'): return 64422, ('ranged' if dmg else 'target')
    if dmg and theme(name): return theme(name), 'ranged'   # a name with an element (Fire Strike, Call Lightning, Frost Nova) is that element's spell, whatever the range
    if dmg:
        ranged = rng == 1 or (rng == 2 and fam in RANGED_FAM)
        if ranged:
            sp = theme(name) or FAM_RANGED.get(fam) or 35387   # Poison Spit as the plain ranged attack of a body creature (lab-accepted for Creeping Fungus)
            return sp, 'ranged'
        return melee_spell(name, fam), 'melee'
    if heal and side != 'enemy': return FAM_HEAL.get(fam, 774), 'self'
    if side == 'self':
        n = name.lower()
        if DEF.search(n): return (22812 if fam in (5, 6) else 6229 if fam in (0, 3) else 871), 'self'
        if DODGE.search(n): return 5277, 'self'
        return 2825, 'self'   # Bloodlust glow: the lab-accepted look of an offensive / speed buff
    if side == 'enemy':
        if theme(name): return theme(name), 'target'
        if rng == 0: return 5211, 'melee'   # a stun / lock by contact: Bash (lab-accepted for Clobber)
        return theme(name) or FAM_RANGED.get(fam) or 4167, 'target'   # Web as the plain debuff
    return None

# ---- inputs
abil = {}
for l in open(S + 'all.tsv'):
    c = l.rstrip('\n').split('\t'); abil[int(c[0])] = dict(name=c[1], fam=int(c[2]) if c[2].isdigit() else -1, dmg=c[3] == '1', heal=c[4] == '1', side=None if c[5] == '-' else c[5])
rngv = {v['ID']: v['RangeTypeEnum'] for v in csv.DictReader(open('pet-battle/retail_data/BattlePetVisual.csv'))}
tv = collections.defaultdict(list)
for t in csv.DictReader(open('pet-battle/retail_data/BattlePetAbilityTurn.csv')):
    r = rngv.get(t['BattlePetVisualID'])
    if r is not None: tv[int(t['BattlePetAbilityID'])].append(int(r))
def retail_range(a): return tv[a][0] if tv.get(a) else 2
lab = collections.defaultdict(list)   # ability -> [(spell, mode, pre, dmg, hop)]
for l in open(S + 'lab.tsv'):
    c = l.rstrip('\n').split('\t')
    if c[4] == 'spell': lab[int(c[0])].append(dict(spell=int(c[5]), mode=c[6] or c[1], pre=int(c[7]) if c[7] else None, hop=c[2] == 'true', item=c[1]))
accepted = {}
for l in list(open('pet-battle/ability_visuals.tsv'))[1:]:
    c = l.rstrip('\n').split('\t')
    if c[2] != 'ACCEPTED': continue
    m = re.search(r'=(\d+)(?:\s*\[([^\]]*)\])?', c[3]); accepted[int(c[0])] = (int(m.group(1)), m.group(2) or '')
HOP = {669}
out, rep, cnt = {}, [], collections.Counter()
for aid in sorted(abil):
    a = abil[aid]; nm = a['name']; rng = retail_range(aid)
    ent = None
    if aid in DEFER: cnt['defer'] += 1; rep.append('%5d %-24s DEFER (choreography)' % (aid, nm)); continue
    if aid in accepted:
        sp, br = accepted[aid]
        cand = next((c for c in lab.get(aid, []) if c['spell'] == sp), None)
        mode = 'aura' if 'aura' in br else 'melee' if 'melee' in br else (cand['mode'] if cand else (lab[aid][0]['item'] if lab.get(aid) else 'melee'))
        if mode in ('lift', 'defer', 'emote'): mode = 'self'
        ent = dict(s=sp, m=mode, pre=cand['pre'] if cand else None, hop=True if aid in HOP else None, dmg=True if sp in DMG else None, src='lab')
    elif nm.lower() not in NAMEBAN and samename(nm) and (a['dmg'] or a['heal'] or a['side']):
        sp = samename(nm); r = rule(nm, a['fam'], a['dmg'], a['heal'], a['side'], rng)
        if r: ent = dict(s=sp, m=r[1], dmg=True if sp in DMG else None, src='name')
    if ent is None:
        r = rule(nm, a['fam'], a['dmg'], a['heal'], a['side'], rng)
        if r: ent = dict(s=r[0], m=r[1], dmg=True if r[0] in DMG else None, src='rule')
    if ent: out[aid] = ent; cnt[ent['src']] += 1
    else: cnt['none'] += 1
    rep.append('%5d %-24s fam=%-9s rng=%d %s%s%s -> %s' % (aid, nm[:24], FAM.get(a['fam'], '?')[:9], rng, 'D' if a['dmg'] else '-', 'H' if a['heal'] else '-', (a['side'] or '-')[:1], ('%s %s %s' % (ent['src'], ent['m'], ent['s'])) if ent else 'none'))
print('\n'.join(rep)); print(dict(cnt), file=sys.stderr)
def lua(e):
    return '{ ' + ', '.join('%s = %s' % (k, ('"%s"' % v) if isinstance(v, str) else ('true' if v is True else v)) for k, v in e.items() if v is not None) + ' }'
open('scripts/pb_vis.lua', 'w').write('-- GENERATED by pet-battle/gen_vis.py (do not edit): presentation of every retail ability. s = visual spell, m = mode (melee/ranged/self/target/aura), pre = a caster-side spell first,\n'
    '-- hop = jump back instead of running, dmg = the spell itself deals damage (a MISS may be re-cast), src = lab (the user accepted it) / name (same-name spell) / rule (kind x range x family).\nlocal V = {}\n'
    + '\n'.join('V[%d] = %s' % (k, lua(v)) for k, v in sorted(out.items())) + '\nreturn V\n')
