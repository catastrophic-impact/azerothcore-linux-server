#!/usr/bin/env python3 -I
"""Generates scripts/pb_scale_caps.lua: for every pet species the VISIBLE WIDTH of its model at scale 1 (client DBC: CreatureModelData bounding box x CreatureDisplayInfo model scale),
so pb_store can scale every pet to the same visible size (biggest dimension = PET_SIZE yards). (The old size table only used creature_model_info bounding radius, which is badly off for sprawling models:
a Forest Spider came out 3.35 yd wide.) Input: release/data/dbc + pet-battle/.s/scales.tsv (species list) + pet-battle/.s/entry_display.tsv (entry<TAB>display id of model row 0, dumped from creature_template_model).
Usage (project root): python3 -I pet-battle/gen_scale_caps.py"""
import struct, re
CDI = 'pet-battle/.s/cdbc/DBFilesclient/Creaturedisplayinfo.dbc'; CMD = 'pet-battle/.s/cdbc/DBFilesclient/Creaturemodeldata.dbc'   # the client's patched DBC (not the server's copy)
# MEASURED in game 2026-11-21 (.pbk grid screenshot): the 3.3.5 client ignores a display scale below ~0.22 (Crab / Duskbats with 0.1-0.2 were drawn 5-10x too big; 0.25 and up are honored)
MIN_K = 0.22
def EFF(k): return k if k >= MIN_K else 1.0
def rows(p):
    d = open(p, 'rb').read(); m, n, f, rs, ss = struct.unpack('<4sIIII', d[:20]); body = d[20:20 + n * rs]
    for i in range(n): yield struct.unpack('<%dI' % f, body[i * rs:(i + 1) * rs])
fl = lambda x: struct.unpack('<f', struct.pack('<I', x))[0]
disp = {r[0]: r for r in rows(CDI)}
mod = {r[0]: r for r in rows(CMD)}
species = set(int(l.split()[0]) for l in open('pet-battle/.s/scales.tsv') if l.strip())   # every stand-in species (dumped from the live server)
ms = {int(l.split()[0]): float(l.split()[1]) for l in open('pet-battle/.s/model_size.tsv')}   # model id -> true silhouette size S (pet-battle/gen_model_size.py)
out = {}
for l in open('pet-battle/.s/entry_display.tsv'):
    p = l.split()
    if len(p) != 2 or not p[0].isdigit(): continue
    e, d = int(p[0]), int(p[1])
    if e not in species or d not in disp or disp[d][1] not in mod: continue
    r = disp[d]; m = mod[r[1]]; k = EFF((fl(r[4]) or 1.0) * (fl(m[4]) or 1.0))
    mn = [fl(x) for x in m[17:20]]; mx = [fl(x) for x in m[20:23]]
    w = max(mx[0] - mn[0], mx[1] - mn[1]) * k; h = (mx[2] - mn[2]) * k
    S = ms.get(r[1])
    if max(w, h) > 0.05 or S: out[e] = (round(max(w, 0.0), 4), round(max(h, 0.0), 4), round(S * k, 4) if S else 0)
lines = ["-- GENERATED by pet-battle/gen_scale_caps.py - do not edit. Visible model { box width, box height, true silhouette size S } in yards at scale 1, per species (S = 0 when the mesh could not be measured).", "return {"]
lines += ["    [%d] = { %s, %s, %s }," % (e, out[e][0], out[e][1], out[e][2]) for e in sorted(out)]
lines.append("}")
open('scripts/pb_scale_caps.lua', 'w').write("\n".join(lines) + "\n")
print("scripts/pb_scale_caps.lua written (%d of %d species)" % (len(out), len(species)))
# per-DISPLAY true size: a species can show several different models (the Crab has 4); the scale must follow the model that is actually on screen, not model row 0
dsz = {}
for l in open('pet-battle/.s/entry_displays_all.tsv'):
    p = l.split()
    if len(p) != 3 or int(p[0]) not in species: continue
    d = int(p[2])
    if d in dsz or d not in disp or disp[d][1] not in mod: continue
    k = EFF((fl(disp[d][4]) or 1.0) * (fl(mod[disp[d][1]][4]) or 1.0)); S = ms.get(disp[d][1])
    if S: dsz[d] = round(S * k, 4)
lines = ["-- GENERATED by pet-battle/gen_scale_caps.py - do not edit. True silhouette size S (yards, at scale 1) per creature DISPLAY id.", "return {"]
lines += ["    [%d] = %s," % (d, dsz[d]) for d in sorted(dsz)]
lines.append("}")
open('scripts/pb_scale_displays.lua', 'w').write("\n".join(lines) + "\n")
print("scripts/pb_scale_displays.lua written (%d displays)" % len(dsz))
