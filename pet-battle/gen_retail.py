#!/usr/bin/env python3 -I
"""Generate scripts/pb_retail.lua (pure data) from the wago.tools DB2 CSVs in pet-battle/retail_data/.
Usage: python3 -I pet-battle/gen_retail.py <species_id> [<species_id> ...]     (retail BattlePetSpecies IDs; see pet-battle/elwynn_kits.tsv)
Emits: families, species (family, base stats, ability slots/levels) and every ability they use with its turns/effects (params labelled)."""
import csv, collections, sys
d = 'pet-battle/retail_data/'
R = lambda n: list(csv.DictReader(open(d + n + '.csv', encoding='utf-8')))
spc = {s['ID']: s for s in R('BattlePetSpecies')}
cr = {c['ID']: c for c in R('Creature')}
ab = {a['ID']: a for a in R('BattlePetAbility')}
tu = collections.defaultdict(list)
for t in R('BattlePetAbilityTurn'): tu[t['BattlePetAbilityID']].append(t)
ef = collections.defaultdict(list)
for e in R('BattlePetAbilityEffect'): ef[e['BattlePetAbilityTurnID']].append(e)
pr = {p['ID']: p for p in R('BattlePetEffectProperties')}
st = {s['ID']: s['LuaName'] for s in R('BattlePetState')}
sx = collections.defaultdict(list)
for x in R('BattlePetSpeciesXAbility'): sx[x['BattlePetSpeciesID']].append(x)
ss = collections.defaultdict(dict)
for x in R('BattlePetSpeciesState'): ss[x['BattlePetSpeciesID']][st.get(x['BattlePetStateID'], x['BattlePetStateID'])] = int(x['Value'])
PT = ['Humanoid', 'Dragonkin', 'Flying', 'Undead', 'Critter', 'Magic', 'Elemental', 'Beast', 'Aquatic', 'Mechanical']
q = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'
ids = sys.argv[1:]
need = set()
out = ['-- GENERATED by pet-battle/gen_retail.py from the wago.tools DB2 tables (retail pet battle data). Do not edit by hand.', 'local R = { species = {}, abilities = {}, effects = {} }']
abst = collections.defaultdict(dict)
for x in R('BattlePetAbilityState'): abst[x['BattlePetAbilityID']][st.get(x['BattlePetStateID'], x['BattlePetStateID'])] = int(x['Value'])
for sid in ids:
    s = spc[sid]; c = cr.get(s['CreatureID'], {})
    slots = [(int(x['SlotEnum']), int(x['RequiredLevel']), x['BattlePetAbilityID']) for x in sx[sid]]
    for _, _, a in slots: need.add(a)
    out.append('R.species[%s] = { name = %s, family = %s, stats = { %s }, abil = { %s } }' % (sid, q(c.get('Name_lang', '?')), q(PT[int(s['PetTypeEnum'])]),
        ', '.join('%s = %d' % (k, v) for k, v in sorted(ss[sid].items())), ', '.join('{ %d, %d, %s }' % t for t in sorted(slots))))
eff_used = set()
def expand(need):
    todo = set(need)
    while todo:
        a = todo.pop()
        for t in tu[a]:
            for e in ef[t['ID']]:
                x = e['AuraBattlePetAbilityID']
                if x != '0' and x not in need: need.add(x); todo.add(x)
expand(need)
out.append('R.stateNames = { %s }' % ', '.join('[%s] = "%s"' % (k, v) for k, v in sorted(st.items(), key=lambda kv: int(kv[0]))))
out.append('R.states = {}')
for a in sorted(need, key=int):
    if abst.get(a): out.append('R.states[%s] = { %s }' % (a, ', '.join('%s = %d' % (k, v) for k, v in sorted(abst[a].items()))))
for a in sorted(need, key=int):
    A = ab[a]; turns = []
    for t in sorted(tu[a], key=lambda t: int(t['OrderIndex'])):
        es = []
        for e in sorted(ef[t['ID']], key=lambda e: int(e['OrderIndex'])):
            eff_used.add(e['BattlePetEffectPropertiesID'])
            es.append('{ prop = %s, aura = %s, p = { %s } }' % (e['BattlePetEffectPropertiesID'], e['AuraBattlePetAbilityID'], ', '.join(e['Param_%d' % i] for i in range(6))))
        turns.append('{ turn = %s, event = %s, fx = { %s } }' % (t['TurnTypeEnum'], t['EventTypeEnum'], ', '.join(es)))
    out.append('R.abilities[%s] = { name = %s, family = %d, cd = %s, text = %s, turns = { %s } }' % (a, q(A['Name_lang']), int(A['PetTypeEnum']), A['Cooldown'], q(A['Description_lang']), ', '.join(turns)))
for p in sorted(eff_used, key=int):
    P = pr[p]
    out.append('R.effects[%s] = { %s }' % (p, ', '.join(q(P['ParamLabel_%d' % i]) for i in range(6) if P['ParamLabel_%d' % i])))
out.append('return R')
open('scripts/pb_retail.lua', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('species', len(ids), 'abilities', len(need), 'effect types', len(eff_used))
