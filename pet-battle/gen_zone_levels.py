#!/usr/bin/env python3 -I
# Regenerates addons/wotlk_pets/ZoneLevels.lua from pet-battle/zone_ranges.tsv + the <zone>_roster.tsv files (include Y):
#   WotlkPetZoneLevels[zone name] = { pet lo, pet hi, mob min, mob max }   (map tooltip)
#   WotlkPetZoneGroups = { { continent, { zone names } } }                  (journal zone filter menu)
#   WotlkPetSpeciesZones[species id] = { zone names }                       (journal zone filter + "Found in" line)
# Run after adding zones / editing rosters.
import os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
rows, keys = {}, {}
for l in open(os.path.join(root, 'pet-battle/zone_ranges.tsv')):
    f = l.rstrip('\n').split('\t')
    if l.startswith('#') or len(f) < 13 or f[8] in ('-', '') or f[12] in rows: continue
    rows[f[12]] = tuple(int(x) for x in f[8:12]); keys[f[0]] = (f[12], f[2])
EK_530 = {'eversong', 'ghostlands'}
OUTLAND = {'hellfire', 'zangarmarsh', 'terokkar', 'nagrand', 'bladesedge', 'netherstorm', 'shadowmoon'}   # map 530 zones that are Outland (Eversong/Ghostlands are Eastern Kingdoms, Azuremyst/Bloodmyst Kalimdor)
groups = {'Eastern Kingdoms': [], 'Kalimdor': [], 'Outland': [], 'Northrend': []}
for key, (name, m) in keys.items():
    groups['Northrend' if m == '571' else 'Outland' if key in OUTLAND else 'Eastern Kingdoms' if (m == '0' or key in EK_530) else 'Kalimdor'].append(name)
species = {}
for key, (name, m) in keys.items():
    path = os.path.join(root, 'pet-battle', key + '_roster.tsv')
    if not os.path.exists(path): continue
    for l in open(path):
        f = l.rstrip('\n').split('\t')
        if l.startswith('#') or len(f) < 3 or f[0].strip().upper() != 'Y' or not f[1].isdigit(): continue
        z = species.setdefault(int(f[1]), [])
        if name not in z: z.append(name)
q = lambda n: n.replace('"', '\\"')
out = '-- Generated by pet-battle/gen_zone_levels.py (zone_ranges.tsv + rosters). Do not edit.\nWotlkPetZoneLevels = {\n'
for n, v in sorted(rows.items()): out += '    ["%s"] = { %d, %d, %d, %d },\n' % ((q(n),) + v)
out += '}\nWotlkPetZoneGroups = {\n'
for g, zs in groups.items(): out += '    { "%s", { %s } },\n' % (g, ', '.join('"%s"' % q(z) for z in sorted(zs)))
out += '}\nWotlkPetSpeciesZones = {\n'
for sp in sorted(species): out += '    [%d] = { %s },\n' % (sp, ', '.join('"%s"' % q(z) for z in sorted(species[sp])))
open(os.path.join(root, 'addons/wotlk_pets/ZoneLevels.lua'), 'w').write(out + '}\n')
print(len(rows), 'zones', len(species), 'species mapped', {g: len(z) for g, z in groups.items()})
