#!/usr/bin/env python3 -I
"""Builds pet-battle/lab/pb_review_data.lua: the ability REVIEW list (every ability whose presentation was made by a rule or a same-name spell, i.e. not yet seen by the user),
ordered by (spell, mode) pair so similar looks are judged together. Run from the repo root: python3 -I pet-battle/review_build.py"""
import re, struct, collections
def dbc(name):
    d = open('release/data/dbc/%s.dbc' % name, 'rb').read(); _, c, f, rs, ss = struct.unpack('<4sIIII', d[:20])
    recs = [struct.unpack_from('<%dI' % f, d, 20 + i * rs) for i in range(c)]; sb = 20 + c * rs
    return recs, (lambda off: d[sb + off:d.index(b'\0', sb + off)].decode('latin1'))
SP, sps = dbc('Spell'); sname = {r[0]: sps(r[136]) for r in SP}
vis = {}
for l in open('scripts/pb_vis.lua'):
    m = re.match(r'V\[(\d+)\] = \{(.*)\}', l)
    if not m: continue
    d = dict(re.findall(r'(\w+) = ("?[\w]+"?)', m.group(2)))
    vis[int(m.group(1))] = {k: v.strip('"') for k, v in d.items()}
ab = {}
for m in re.finditer(r'R\.abilities\[(\d+)\] = \{ name = "((?:[^"\\]|\\.)*)", family = (-?\d+), cd = \d+, text = "((?:[^"\\]|\\.)*)"', open('scripts/pb_retail.lua').read() + open('scripts/pb_wild_kits.lua').read()):
    t = re.sub(r'\[[^\]]*\]', 'X', m.group(4)); t = re.sub(r'\|c[0-9a-fA-F]{8}|\|r', '', t); t = re.sub(r'\s+', ' ', t).strip()
    ab[int(m.group(1))] = (m.group(2), t)
items = []
for aid, v in vis.items():
    if v.get('src') not in ('rule', 'name') or aid not in ab: continue
    sp = int(v['s']); mode = v['m']
    c = dict(kind='spell', spell=sp, label=sname.get(sp, 'spell %d' % sp), mode=mode)
    if v.get('dmg') == 'true': c['dmg'] = True
    if v.get('pre'): c['pre'] = int(v['pre'])
    items.append(dict(id=aid, name=ab[aid][0], text=ab[aid][1], species=299, mode=mode, hits=1, hop=True if v.get('hop') == 'true' else None, grp='%s [%s]' % (c['label'], mode), cands=[c], src=v['src']))
order = collections.OrderedDict()
for it in sorted(items, key=lambda x: (x['grp'], x['id'])): order.setdefault(it['grp'], []).append(it)
def lua(x):
    if isinstance(x, dict): return '{' + ', '.join('%s = %s' % (k, lua(v)) for k, v in x.items() if v is not None) + '}'
    if isinstance(x, list): return '{' + ', '.join(lua(v) for v in x) + '}'
    if isinstance(x, bool): return 'true' if x else 'false'
    if isinstance(x, str): return '"' + x.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return str(x)
rows = [it for g in order.values() for it in g]
open('pet-battle/lab/pb_review_data.lua', 'w').write('-- GENERATED by pet-battle/review_build.py (do not edit)\nreturn {\n' + ',\n'.join(lua(r) for r in rows) + '\n}\n')
print(len(rows), 'abilities in', len(order), 'spell+mode groups')
