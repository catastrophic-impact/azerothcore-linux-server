#!/usr/bin/env python3
"""Fourth decor pass: visual-effect models (glow/smoke/steam/beam/fire/mist...) from GameObjectDisplayInfo.dbc that pass 3 skipped, as OUR OWN inert
type-5 templates (entries 920000+) -> custom-sql/009_decor_effects.sql, sheet rows include R (Removed shelf for review), note pass4.
gen_garrison_catalog.py gives pass4 items a default view box (emitters have no vertices). Re-runnable (own rows are regenerated).
usage: find_decor_effects.py [release_dir] [--dry]"""
import os, re, struct, sys
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = [a for a in sys.argv[1:] if not a.startswith('--')]; dry = '--dry' in sys.argv
rel = args[0] if args else os.path.join(proj, 'release')
d = open(os.path.join(rel, 'data', 'dbc', 'GameObjectDisplayInfo.dbc'), 'rb').read()
_, n, nf, rs, ss = struct.unpack('<4sIIII', d[:20]); strs = d[20 + n * rs:]; model = {}
for i in range(n):
    r = struct.unpack_from('<%dI' % nf, d, 20 + i * rs)
    model[r[0]] = re.sub(r'(?i)\.(mdx|mdl)$', '.m2', strs[r[1]:strs.index(b'\0', r[1])].decode())
sheet = os.path.join(proj, 'decor-proposals', 'decor.tsv'); lines = open(sheet).read().splitlines()
haveD, haveF, mine = set(), set(), {}
for l in lines[1:]:
    c = l.split('\t')
    if len(c) < 6: continue
    if len(c) > 12 and c[12] == 'pass4': mine[int(c[5])] = int(c[4]); continue
    haveD.add(int(c[5])); haveF.add(c[9].lower())
FX = re.compile(r'(glow|smoke|steam|fog|aura|beam|particle|effect|\bfx|_fx|spark|flare|fire|flame|waterfall|lava|geyser|bubble|swirl|energy|\borb|\bray|shaft|vortex|rift|mist|cloud|embers|ghost|magic|rune|light|lightning|shimmer|dust|snow|rain|ice ?crystal|portal|sigil|spell|splash|ripple|torch|candle|brazier)', re.I)
HARD = re.compile(r'(\.wmo$|[\\/]gm|collision|invisible|trigger|dummy|test|unused|placeholder|spawn|transport|elevator|zeppelin|boat|ship|door|teleport|camera|marker|worldtrigger)', re.I)
def pretty(p):
    f = re.sub(r'\.m2$', '', p.split('\\')[-1], flags=re.I).replace('_', ' ')
    return re.sub(r'\s+', ' ', re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', f)).strip().title()[:60]
BASE = 920000; nxt = max([BASE - 1] + list(mine.values())) + 1
new, seen = [], set()
for dp in sorted(model):
    m = model[dp]
    if not m or dp in haveD or HARD.search(m) or not FX.search(m): continue
    fn = m.split('\\')[-1].lower()
    if fn in haveF or fn in seen: continue
    seen.add(fn); e = mine.get(dp)
    if e is None: e = nxt; nxt += 1
    new.append((e, dp, pretty(m), m))
if not new: sys.exit('nothing to add')
print(len(new), 'effect models (entries %d-%d)' % (new[0][0], new[-1][0]))
if dry:
    for e, dp, nm, m in new[::max(1, len(new) // 30)]: print(nm, '|', m)
    sys.exit()
with open(os.path.join(proj, 'custom-sql', '009_decor_effects.sql'), 'w') as f:
    f.write('-- GENERATED by tools/find_decor_effects.py: inert generic templates (920000+) for visual-effect models. Idempotent.\nUSE acore_world;\nDELETE FROM gameobject_template WHERE entry BETWEEN %d AND %d;\n' % (BASE, new[-1][0]))
    for i in range(0, len(new), 200):
        f.write('INSERT INTO gameobject_template (entry, type, displayId, name, IconName, castBarCaption, unk1, size, AIName, ScriptName, VerifiedBuild) VALUES\n')
        f.write(',\n'.join("(%d, 5, %d, '%s', '', '', '', 1, '', '', 12340)" % (e, dp, nm.replace("'", "''")) for e, dp, nm, m in new[i:i + 200]) + ';\n')
keep = [l for l in lines if l.split('\t')[12:13] != ['pass4']]
with open(sheet, 'w') as f:
    f.write('\n'.join(keep) + '\n')
    for e, dp, nm, m in new: f.write('\t'.join(map(str, ('R', 'Neutral', 'Effects', nm, e, dp, 5, 1, 1, m.split('\\')[-1], '', m, 'pass4'))) + '\n')
print('wrote custom-sql/009_decor_effects.sql and', len(new), 'sheet rows')
