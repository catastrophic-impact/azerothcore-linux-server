#!/usr/bin/env python3
"""Eighth decor pass: EVERY remaining non-WMO model in GameObjectDisplayInfo.dbc that is not yet in decor-proposals/decor.tsv (the ones passes 1-7 filtered out:
doors, elevators, collision walls, effects, PvP banners, trade-skill nodes ...) gets OUR OWN inert type-5 template (entries 960001+, custom-sql/013_decor_rest.sql)
and a sheet row (Y, Unsorted, note pass8) so it can be reviewed in Curator mode. A model whose FILE is already in the sheet under another display id is skipped (same model).
Stable: re-running keeps entries. usage: find_decor_rest.py [--dry]"""
import os, re, struct, sys
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); rel = os.path.join(proj, 'release'); dry = '--dry' in sys.argv
d = open(os.path.join(rel, 'data', 'dbc', 'GameObjectDisplayInfo.dbc'), 'rb').read()
_, n, nf, rs, ss = struct.unpack('<4sIIII', d[:20]); strs = d[20 + n * rs:]; model = {}
for i in range(n):
    r = struct.unpack_from('<%dI' % nf, d, 20 + i * rs)
    model[r[0]] = re.sub(r'(?i)\.(mdx|mdl)$', '.m2', strs[r[1]:strs.index(b'\0', r[1])].decode('latin1'))
sheet = os.path.join(proj, 'decor-proposals', 'decor.tsv'); lines = open(sheet).read().splitlines()
haveD, haveF, mine = set(), set(), {}
for l in lines[1:]:
    c = l.split('\t')
    if len(c) < 6: continue
    if len(c) > 12 and c[12] == 'pass8': mine[int(c[5])] = int(c[4]); continue
    haveD.add(int(c[5])); haveF.add(c[9].lower().replace('.mdx', '.m2').replace('.mdl', '.m2'))
def pretty(p):
    f = re.sub(r'\.(m2|mdx|mdl)$', '', p.split('\\')[-1], flags=re.I).replace('_', ' ')
    f = re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', f)
    return re.sub(r'\s+', ' ', f).strip().title()[:60]
used = set(mine.values()); nxt = max([960000] + list(used)) + 1
new, seen, dup = [], set(), 0
for dp in sorted(model):
    m = model[dp]
    if not m or dp in haveD or m.lower().endswith('.wmo') or m.lower().endswith('.m2') is False: continue
    fn = m.split('\\')[-1].lower()
    if fn in haveF or fn in seen: dup += 1; continue
    seen.add(fn)
    e = mine.get(dp)
    if e is None: e = nxt; nxt += 1
    new.append((e, dp, pretty(m), m))
print(len(new), 'new models,', dup, 'skipped as the same model file as one already in the sheet')
if dry or not new: sys.exit()
with open(os.path.join(proj, 'custom-sql', '013_decor_rest.sql'), 'w') as f:
    f.write('-- GENERATED by tools/find_decor_rest.py: inert type-5 templates (960001+) for the remaining client models. Idempotent.\nUSE acore_world;\nDELETE FROM gameobject_template WHERE entry BETWEEN 960001 AND 969999;\n')
    for i in range(0, len(new), 200):
        f.write('INSERT INTO gameobject_template (entry, type, displayId, name, IconName, castBarCaption, unk1, size, AIName, ScriptName, VerifiedBuild) VALUES\n')
        f.write(',\n'.join("(%d, 5, %d, '%s', '', '', '', 1, '', '', 12340)" % (e, dp, nm.replace("'", "''")) for e, dp, nm, m in new[i:i + 200]) + ';\n')
keep = [l for l in lines if l.split('\t')[12:13] != ['pass8']]
with open(sheet, 'w') as f:
    f.write('\n'.join(keep) + '\n')
    for e, dp, nm, m in new: f.write('\t'.join(map(str, ('Y', 'Neutral', 'Unsorted', nm, e, dp, 5, 1, 1, m.split('\\')[-1], '', m, 'pass8'))) + '\n')
print('wrote custom-sql/013_decor_rest.sql and', len(new), 'sheet rows')
