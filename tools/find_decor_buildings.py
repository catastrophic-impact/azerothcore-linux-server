#!/usr/bin/env python3
"""Adds every whole-building model (WMO) in GameObjectDisplayInfo.dbc to the garrison decor sheet as category Unsorted (hidden from players until sorted in the admin tool).
Displays that already have a placeable template (type 5 or 14) use it; the rest get a new static template (entry 950001+, written to custom-sql/012_decor_buildings.sql).
Ships, zeppelins and elevators (transports) are skipped. Safe to re-run.
usage: find_decor_buildings.py     env: ACORE_PREFIX (e.g. 'flatpak-spawn --host')"""
import os, re, struct, subprocess
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); rel = os.path.join(proj, 'release')
FIRST = 950001
def sql(q): return subprocess.run(os.environ.get('ACORE_PREFIX', '').split() + [os.path.join(rel, 'acore-admin'), 'sql', q], capture_output=True, text=True, check=True).stdout
d = open(os.path.join(rel, 'data', 'dbc', 'GameObjectDisplayInfo.dbc'), 'rb').read()
_, n, nf, rs, ss = struct.unpack('<4sIIII', d[:20]); sb = 20 + n * rs; wmo = {}
for i in range(n):
    r = d[20 + i * rs:20 + (i + 1) * rs]; did, off = struct.unpack('<II', r[:8]); m = d[sb + off:d.index(b'\0', sb + off)].decode('latin1')
    if m.lower().endswith('.wmo') and 'transport' not in m.lower(): wmo[did] = m
tmpl = {}
for l in sql("select displayId,entry,type,name from acore_world.gameobject_template where type in (5,14) and entry<950000 and displayId in (%s) order by entry" % ','.join(map(str, wmo))).splitlines():
    did, e, t, nm = l.split('\t'); tmpl.setdefault(int(did), (int(e), int(t), nm))
sheet = os.path.join(proj, 'decor-proposals', 'decor.tsv'); lines = open(sheet).read().splitlines()
known = {l.split('\t')[4] for l in lines[1:] if len(l.split('\t')) > 4 and l.split('\t')[0].strip().upper() in ('Y', 'R')}   # earlier automatic rejections (N) are re-added
def pretty(path):
    b = re.sub(r'\.wmo$', '', path.replace('\\', '/').split('/')[-1], flags=re.I).replace('_', ' ')
    return re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', b).strip().title()
rows, ins, nxt = [], [], FIRST
for did in sorted(wmo):
    if did in tmpl: e, t, nm = tmpl[did]
    else: e, t, nm = nxt, 5, pretty(wmo[did]); nxt += 1; ins.append((e, did, nm))
    if str(e) in known: continue
    rows.append('\t'.join(['Y', 'Neutral', 'Unsorted', (nm or pretty(wmo[did])), str(e), str(did), str(t), '1', '1', os.path.basename(wmo[did].replace('\\', '/')), '', wmo[did], 'building (WMO)']))
with open(os.path.join(proj, 'custom-sql', '012_decor_buildings.sql'), 'w') as f:
    f.write('-- Whole-building models (WMO) from GameObjectDisplayInfo as static gameobjects, for garrison decor. GENERATED by tools/find_decor_buildings.py. Re-running is safe.\nUSE `acore_world`;\n')
    for e, did, nm in ins: f.write("REPLACE INTO `gameobject_template` (`entry`,`type`,`displayId`,`name`,`size`) VALUES (%d,5,%d,'%s',1);\n" % (e, did, nm.replace("'", "''")))
open(sheet, 'a').write('\n'.join(rows) + ('\n' if rows else ''))
print('%d building models: %d use an existing template, %d new templates (entry %d-%d); %d rows added to decor.tsv' % (len(wmo), len(wmo) - len(ins), len(ins), FIRST, nxt - 1, len(rows)))
