#!/usr/bin/env python3
"""Generate the shop catalog (server Lua + addon Lua) from shop-proposals/*.tsv + shop-config.json.
Reads icons/models from the client DBCs in <release>/data/dbc and creature display ids from the world DB.
usage: gen_shop_catalog.py [release_dir]      env: ACORE_PREFIX (e.g. 'flatpak-spawn --host') for running acore-admin"""
import json, os, struct, subprocess, sys
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rel = sys.argv[1] if len(sys.argv) > 1 else os.path.join(proj, 'release')
cfg = json.load(open(os.path.join(proj, 'shop-config.json')))

def dbc(name):
    d = open(os.path.join(rel, 'data', 'dbc', name), 'rb').read()
    magic, n, nf, rs, ss = struct.unpack('<4sIIII', d[:20]); assert magic == b'WDBC'
    strs = d[20 + n * rs:20 + n * rs + ss]
    def s(off): return strs[off:strs.index(b'\0', off)].decode('utf8', 'replace')
    return n, nf, rs, d, s
def records(name):
    n, nf, rs, d, s = dbc(name)
    for r in range(n): yield struct.unpack_from('<%dI' % nf, d, 20 + r * rs), s

# item -> display -> icon
item_disp = {r[0]: r[5] for r, _ in records('Item.dbc')}
disp_icon = {}
for r, s in records('ItemDisplayInfo.dbc'):
    disp_icon[r[0]] = s(r[5])
# spell -> creature entry (summon effect 28 / mounted aura 78 misc value)
spell_npc = {}
for r, _ in records('Spell.dbc'):
    for e in range(3):
        eff, aura, misc = r[71 + e], r[95 + e], r[110 + e]
        if misc and (eff == 28 or (eff == 6 and aura == 78)):
            spell_npc.setdefault(r[0], misc)

def sql(q):
    admin = os.path.join(rel, 'acore-admin')
    cmd = (os.environ.get('ACORE_PREFIX', '').split() + [admin, 'sql', q])
    return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout

def read(fn):
    rows = []
    for l in open(os.path.join(proj, 'shop-proposals', fn)).read().splitlines()[1:]:
        c = l.split('\t')
        if len(c) >= 9 and c[0].upper() == 'Y':
            rows.append(dict(kind=c[1], item=int(c[2]), name=c[3], quality=int(c[4]), spell=int(c[5] or 0), vf=c[7]))
    return rows

rows = read('A_no-source.tsv')
bfile = read('B_one-faction-vendor.tsv')
rows += [r for r in bfile if r['kind'] == 'pet' and cfg['includeFactionPets']]
rows += [r for r in bfile if r['kind'] == 'mount' and cfg['includeFactionMounts']]
# Resolve the REAL companion/mount spell per item: skip generic "Learning"(483)/"Learn"(55884) slots and anything that
# does not lead to a summoned creature or mounted aura (toys, crafting-recipe items, junk) -> those are dropped.
ids = sorted({r['item'] for r in rows})
isp = {}
for l in sql('select entry,spellid_1,spellid_2,spellid_3 from acore_world.item_template where entry in (%s)' % ','.join(map(str, ids))).splitlines():
    c = l.split('\t'); isp[int(c[0])] = [int(x) for x in c[1:4]]
seen, out, dropped = set(), {'pet': [], 'mount': []}, []
for r in sorted(rows, key=lambda r: r['name'].lower()):
    sp = next((s for s in isp.get(r['item'], []) if s not in (0, 483, 55884) and s in spell_npc), 0)
    if not sp:
        dropped.append(r['name']); continue
    r['spell'] = sp
    key = (r['kind'], sp)
    if key in seen: continue                             # duplicate items teaching the same spell
    seen.add(key)
    r['npc'] = spell_npc[sp]
    r['icon'] = disp_icon.get(item_disp.get(r['item'], 0), '') or 'INV_Misc_QuestionMark'
    p = cfg['prices']
    r['cost'] = p['pet'] if r['kind'] == 'pet' else (p['mountEpic'] if r['quality'] >= 4 else p['mountCommon'])
    out[r['kind']].append(r)
if dropped: print('DROPPED (no companion/mount effect):', ', '.join(dropped))
npcs = sorted({r['npc'] for k in out for r in out[k] if r['npc']})
disp = {}
if npcs:
    for l in sql('select CreatureID, CreatureDisplayID from acore_world.creature_template_model where CreatureID in (%s) order by Idx' % ','.join(map(str, npcs))).splitlines():
        a, b = l.split('\t'); disp.setdefault(int(a), int(b))
for k in out:
    for r in out[k]: r['display'] = disp.get(r['npc'], 0)

def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
toys = cfg.get('toys', [])
# ---- server ----
S = ['-- GENERATED by tools/gen_shop_catalog.py from shop-proposals + shop-config.json. Do not edit by hand.',
     'return {', '    npcs = { %s },' % ', '.join(map(str, npcs)), '    tabs = {']
for tab, kind, base in (('pets', 'pet', 1000), ('mounts', 'mount', 2000)):
    S.append('        %s = {' % tab)
    for i, r in enumerate(out[kind], 1):
        S.append('            { id = %d, item = %d, spell = %d, name = %s, cost = %d },' % (base + i, r['item'], r['spell'], q(r['name']), r['cost']))
    S.append('        },')
S.append('        services = {')
for i, sv in enumerate(cfg.get('services', []), 1):
    S.append('            { id = %d, service = %s, name = %s, cost = 0, message = %s },' % (4000 + i, q(sv['key']), q(sv['name']), q(sv['message'])))
S.append('        },')
S.append('        toys = {')
for i, t in enumerate(toys, 1):
    S.append('            { id = %d, item = %d, count = %d, name = %s, cost = %d },' % (3000 + i, t['item'], t.get('count', 1), q(t['name']), t['cost']))
S += ['        },', '    },', '}', '']
open(os.path.join(proj, 'scripts', 'shop_catalog.lua'), 'w').write('\n'.join(S))
# ---- client ----
C = ['-- GENERATED by tools/gen_shop_catalog.py. Do not edit by hand.',
     'WotlkShopCatalog = {', '    tabs = { "pets", "mounts", "toys", "services" },',
     '    titles = { pets = "Forgotten Pets", mounts = "Forgotten Mounts", toys = "Toys", services = "Services" },', '    items = {']
for tab, kind, base in (('pets', 'pet', 1000), ('mounts', 'mount', 2000)):
    C.append('        %s = {' % tab)
    for i, r in enumerate(out[kind], 1):
        C.append('            { id = %d, item = %d, name = %s, cost = %d, icon = %s, display = %d, npc = %d },' % (base + i, r['item'], q(r['name']), r['cost'], q(r['icon']), r['display'], r['npc']))
    C.append('        },')
C.append('        toys = {')
for i, t in enumerate(toys, 1):
    ico = disp_icon.get(item_disp.get(t['item'], 0), '') or 'INV_Misc_QuestionMark'
    C.append('            { id = %d, item = %d, name = %s, cost = %d, icon = %s, display = 0, npc = 0 },' % (3000 + i, t['item'], q(t['name']), t['cost'], q(ico)))
C += ['        },', '        services = {']
for i, sv in enumerate(cfg.get('services', []), 1):
    C.append('            { id = %d, item = 0, name = %s, cost = 0, icon = %s, display = 0, npc = 0 },' % (4000 + i, q(sv['name']), q(sv['icon'])))
C += ['        },', '    },', '}', '']
open(os.path.join(proj, 'addons', 'wotlk_shop', 'Catalog.lua'), 'w').write('\n'.join(C))
print('pets', len(out['pet']), 'mounts', len(out['mount']), 'toys', len(toys), '| with icon', sum(r['icon'] != 'INV_Misc_QuestionMark' for k in out for r in out[k]), '| with 3D model', sum(bool(r['display']) for k in out for r in out[k]))
