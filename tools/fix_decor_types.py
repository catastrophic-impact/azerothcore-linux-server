#!/usr/bin/env python3
"""Writes custom-sql/014_decor_types.sql: the game client only draws a script-spawned object when its gameobject TYPE matches the model format
(verified in game 2026-11-10): WMO models need type 14 (map object), M2 models need type 5 (generic). Stock templates and our own were often the other way round
(WMOs as type 5 = checkered cubes; M2 'map objects' of type 14 = invisible). Reads the sheet's ORIGINAL type column, so it is stable and idempotent; entries (kinds) never change.
Entries with real world spawns are never changed (Moonwell 177232 -> own template 970001). usage: fix_decor_types.py"""
import csv, os
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.DictReader(open(os.path.join(proj, 'decor-proposals', 'decor.tsv')), delimiter='\t'))
KEEP = set()
NEW = {970001: (4691, 'Moonwell')}   # the stock Moonwell (177232, type 8) has a real world spawn: its model gets our own type-14 template instead
wmo = sorted({int(r['entry']) for r in rows if r['include'] in ('Y', 'R') and r['modelpath'].lower().endswith('.wmo') and r['type'] != '14' and r['entry'] not in KEEP})
m2 = sorted({int(r['entry']) for r in rows if r['include'] in ('Y', 'R') and r['modelpath'].lower().endswith('.m2') and r['type'] == '14'})
def chunks(l, n=100):
    for i in range(0, len(l), n): yield ','.join(map(str, l[i:i + n]))
with open(os.path.join(proj, 'custom-sql', '014_decor_types.sql'), 'w') as f:
    f.write('-- GENERATED by tools/fix_decor_types.py. The client draws a script-spawned object only when its type matches the model format: WMO -> 14, M2 -> 5. Idempotent.\nUSE acore_world;\n')
    for e, (dp, nm) in sorted(NEW.items()): f.write("REPLACE INTO gameobject_template (entry, type, displayId, name, size) VALUES (%d, 14, %d, '%s', 1);\n" % (e, dp, nm))
    for c in chunks(wmo): f.write('UPDATE gameobject_template SET type = 14 WHERE entry IN (%s);\n' % c)
    for c in chunks(m2): f.write('UPDATE gameobject_template SET type = 5 WHERE entry IN (%s);\n' % c)
print(len(wmo), 'WMO entries -> type 14;', len(m2), 'M2 entries -> type 5')
