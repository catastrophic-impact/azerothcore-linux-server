#!/usr/bin/env python3
"""PNG -> BLP2 (DXT1, with mipmaps) for the 3.3.5 client. Pure numpy + Pillow (run with cache/venv/bin/python).
usage: png_to_blp.py <in.png|dir> <out.blp|dir> [addon WmoPreviews.lua to write]   (256x256 or any power of two)"""
import os, struct, sys
import numpy as np
from PIL import Image

def dxt1(rgb):
    h, w, _ = rgb.shape
    b = rgb.reshape(h // 4, 4, w // 4, 4, 3).transpose(0, 2, 1, 3, 4).reshape(-1, 16, 3).astype('i4')
    hi, lo = b.max(axis=1), b.min(axis=1)
    def to565(c): return ((c[:, 0] >> 3) << 11) | ((c[:, 1] >> 2) << 5) | (c[:, 2] >> 3)
    e0, e1 = to565(hi), to565(lo)
    swap = e0 < e1; e0, e1 = np.where(swap, e1, e0), np.where(swap, e0, e1)
    def from565(e): return np.stack([((e >> 11) & 31) * 255 // 31, ((e >> 5) & 63) * 255 // 63, (e & 31) * 255 // 31], axis=1)
    c0, c1 = from565(e0), from565(e1)
    pal = np.stack([c0, c1, (2 * c0 + c1) // 3, (c0 + 2 * c1) // 3], axis=1)   # (n,4,3); with e0 > e1 these are the 4 colors of the block
    d = ((b[:, :, None, :] - pal[:, None, :, :]) ** 2).sum(axis=3)              # (n,16,4)
    idx = d.argmin(axis=2).astype('u4')
    idx[e0 == e1] = 0
    bits = np.zeros(len(b), 'u4')
    for i in range(16): bits |= idx[:, i] << (2 * i)
    out = np.zeros(len(b), dtype=[('c0', '<u2'), ('c1', '<u2'), ('i', '<u4')])
    out['c0'], out['c1'], out['i'] = e0, e1, bits
    return out.tobytes()

def write_blp(im, path):
    im = im.convert('RGB'); w, h = im.size
    levels = []; cur = im
    while True:
        cw, ch = cur.size
        if cw < 4 or ch < 4: break
        levels.append(dxt1(np.asarray(cur)))
        if cw == 4 and ch == 4: break
        cur = im.resize((max(4, cw // 2), max(4, ch // 2)), Image.LANCZOS)
    hdr = 1172; offs = [0] * 16; sizes = [0] * 16; pos = hdr
    for i, d in enumerate(levels[:16]): offs[i], sizes[i] = pos, len(d); pos += len(d)
    head = b'BLP2' + struct.pack('<IBBBBII', 1, 2, 0, 0, 1, w, h) + struct.pack('<16I', *offs) + struct.pack('<16I', *sizes) + b'\0' * 1024
    assert len(head) == hdr
    with open(path, 'wb') as f: f.write(head + b''.join(levels))

if __name__ == '__main__':
    a, b = sys.argv[1], sys.argv[2]
    if os.path.isdir(a):
        os.makedirs(b, exist_ok=True); n = 0
        for f in sorted(os.listdir(a)):
            if f.lower().endswith('.png') and not f.startswith('sheet'): write_blp(Image.open(os.path.join(a, f)), os.path.join(b, f[:-4] + '.blp')); n += 1
        print(n, 'files written to', b)
        if len(sys.argv) > 3:   # list of the kinds that have a picture, for the addon (WotlkGarrison.wmoPic)
            kinds = sorted(f[:-4] for f in os.listdir(b) if f.endswith('.blp'))
            open(sys.argv[3], 'w').write('-- GENERATED by tools/png_to_blp.py: the buildings (WMO) that have a rendered preview picture in wmo/<kind>.blp\nWotlkGarrison.wmoPic = { %s }\n' % ', '.join('%s = true' % k for k in kinds))
    else: write_blp(Image.open(a), b); print('wrote', b, os.path.getsize(b), 'bytes')
