#!/usr/bin/env python3
"""Generate addons/wotlk_jukebox/Tracks.lua from jukebox-proposals/tracks.tsv (include=Y) + durations.tsv (tools/jukebox_durations.py).
Tracks missing from the client or shorter than MIN_SECONDS (stingers) are left out."""
import csv, os, collections
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIN_SECONDS = 20
dur = {l.split('\t')[0]: float(l.split('\t')[1]) for l in open(os.path.join(proj, 'jukebox-proposals', 'durations.tsv'))}
rows = [r for r in csv.DictReader(open(os.path.join(proj, 'jukebox-proposals', 'tracks.tsv')), delimiter='\t') if r['include'].strip().upper() == 'Y']
GROUPS = {'CityMusic': 'Cities', 'ZoneMusic': 'Zones', 'Musical Moments': 'Musical Moments', 'event': 'Events', 'WorldEvents': 'Events'}
areas = collections.OrderedDict(); skipped = 0
for r in rows:
    d = dur.get(r['path'])
    if d is None or d < MIN_SECONDS: skipped += 1; continue
    g = GROUPS.get(r['group'], 'Other')
    area = r['area'] or r['entry_name'].replace('Zone-', '')
    tav = 'Taverns' if area.lower().startswith('tavern') else None
    if tav: g = 'Taverns'; area = area[6:] or area
    key = (g, area, os.path.dirname(r['path'].replace('\\', '/')).replace('/', '\\'))
    areas.setdefault(key, []).append((r['file'], round(d)))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['-- GENERATED by tools/gen_jukebox.py. Do not edit by hand.', 'WotlkJukeboxTracks = {']
for (g, a, dirn), tr in sorted(areas.items(), key=lambda kv: (kv[0][0], kv[0][1].lower())):
    out.append('    { group = %s, area = %s, dir = %s, tracks = { %s } },' % (q(g), q(a), q(dirn), ', '.join('{ %s, %d }' % (q(f), d) for f, d in sorted(tr))))
out += ['}', '']
open(os.path.join(proj, 'addons', 'wotlk_jukebox', 'Tracks.lua'), 'w').write('\n'.join(out))
print(sum(len(t) for t in areas.values()), 'tracks in', len(areas), 'areas;', skipped, 'skipped (missing/short/excluded)')
