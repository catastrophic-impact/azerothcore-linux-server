#!/usr/bin/env python3
"""Generate custom-sql/004_menagerie.sql: world.dc_companion (companion spell -> creature entry) from Spell.dbc + SummonProperties.dbc
(effect 28 summons whose SummonProperties type is 5 = minipet), plus the per-account Menagerie setting table.
usage: gen_companions.py [release_dir]"""
import os, struct, sys
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rel = sys.argv[1] if len(sys.argv) > 1 else os.path.join(proj, 'release')
def dbc(n):
    d = open(os.path.join(rel, 'data', 'dbc', n), 'rb').read(); _, c, f, rs, ss = struct.unpack('<4sIIII', d[:20]); return d, c, f, rs
d, c, f, rs = dbc('SummonProperties.dbc')
mini = {struct.unpack_from('<%dI' % f, d, 20 + i * rs)[0] for i in range(c) if struct.unpack_from('<%dI' % f, d, 20 + i * rs)[3] == 5}
d, c, f, rs = dbc('Spell.dbc')
res = {}
for i in range(c):
    r = struct.unpack_from('<%dI' % f, d, 20 + i * rs)
    for e in range(3):
        if r[71 + e] == 28 and r[110 + e] and r[113 + e] in mini: res[r[0]] = r[110 + e]
out = ['-- GENERATED by tools/gen_companions.py (companion spell -> summoned creature) + Menagerie setting table. Idempotent.',
       'USE acore_world;',
       'CREATE TABLE IF NOT EXISTS dc_companion (spell INT UNSIGNED NOT NULL, npc INT UNSIGNED NOT NULL, PRIMARY KEY (spell)) ENGINE=InnoDB;',
       'DELETE FROM dc_companion;',
       'INSERT INTO dc_companion (spell, npc) VALUES']
out.append(',\n'.join('(%d,%d)' % kv for kv in sorted(res.items())) + ';')
out += ['USE acore_characters;',
        '-- Menagerie: 1 = pets explore the garrison (default), 0 = pets stay home. Per account + location.',
        'CREATE TABLE IF NOT EXISTS dc_garrison_setting (account INT UNSIGNED NOT NULL, location INT UNSIGNED NOT NULL, roam TINYINT NOT NULL DEFAULT 1, PRIMARY KEY (account, location)) ENGINE=InnoDB;', '']
open(os.path.join(proj, 'custom-sql', '004_menagerie.sql'), 'w').write('\n'.join(out))
print(len(res), 'companion spells')
