#!/usr/bin/env python3
"""Third decor pass: every client model (GameObjectDisplayInfo.dbc) not yet in decor-proposals/decor.tsv gets OUR OWN inert generic
gameobject_template (entries 910000+, type 5, no data/script) -> custom-sql/008_decor_templates.sql, and a sheet row (include Y, Unsorted, note pass3).
Stable: an existing displayId keeps its entry (read back from the sheet). Models only (no .wmo), junk/effect/gm/trade-node paths skipped.
usage: find_decor_models.py [release_dir] [--dry]   env: ACORE_PREFIX is not needed (DBC only)"""
import os, re, struct, sys
proj = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = [a for a in sys.argv[1:] if not a.startswith('--')]; dry = '--dry' in sys.argv
rel = args[0] if args else os.path.join(proj, 'release')
d = open(os.path.join(rel, 'data', 'dbc', 'GameObjectDisplayInfo.dbc'), 'rb').read()
_, n, nf, rs, ss = struct.unpack('<4sIIII', d[:20]); strs = d[20 + n * rs:]; model = {}
for i in range(n):
    r = struct.unpack_from('<%dI' % nf, d, 20 + i * rs)
    model[r[0]] = re.sub(r'(?i)\.(mdx|mdl)$', '.m2', strs[r[1]:strs.index(b'\0', r[1])].decode())   # client ships .m2
sheet = os.path.join(proj, 'decor-proposals', 'decor.tsv')
lines = open(sheet).read().splitlines()
haveD, haveF, mine = set(), set(), {}
for l in lines[1:]:
    c = l.split('\t')
    if len(c) < 6: continue
    if len(c) > 12 and c[12] == 'pass3': mine[int(c[5])] = int(c[4]); continue   # our own earlier rows are regenerated, not treated as 'already present'
    haveD.add(int(c[5])); haveF.add(c[9].lower())
BADPATH = re.compile(r'(\.wmo$|skillactivated|tradeskillnodes|[\\/]spells?[\\/]|[\\/]gm|worldtrigger|[\\/]cameras?[\\/]|[\\/]pvp[\\/].*(flag|banner)|zeppelin|boat|ship|elevator|lift|transport|portal|teleport|forcefield|bunny|collision|invisible|trigger|dummy|test|unused|placeholder|spawn|aura|beam|glow|particle|effect|ray|shaft|vortex|rift|sigil|fx\b|_fx|marker|highlight|explosion|smoke|steam|fog|cloud|waterfall|lava|spout|geyser|bubbles|sparkle|flare|fire[a-z]*wall|swirl|energy|orb\b|bossdoor|door)', re.I)
def pretty(p):
    f = re.sub(r'\.(m2|mdx|mdl)$', '', p.split('\\')[-1], flags=re.I).replace('_', ' ')
    f = re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', f)
    return re.sub(r'\s+', ' ', f).strip().title()[:60]
BASE = 910000
used = set(mine.values()); nxt = max([BASE - 1] + list(used)) + 1
new, seen = [], set()
for dp in sorted(model):
    m = model[dp]
    if not m or dp in haveD or BADPATH.search(m): continue
    fn = m.split('\\')[-1].lower().replace('.mdx', '.m2').replace('.mdl', '.m2')
    if fn in haveF or fn in seen: continue
    seen.add(fn)
    if dp in mine: e = mine[dp]
    else: e = nxt; nxt += 1
    new.append((e, dp, pretty(m), m))
if not new: sys.exit('nothing to add; sheet and SQL left untouched')
print(len(new), 'models get our own templates (entries %d-%d)' % (new[0][0], new[-1][0]) if new else 'none')
if dry:
    import random; random.seed(1)
    for e, dp, nm, m in random.sample(new, min(40, len(new))): print(nm, '|', m)
    sys.exit()
# SQL: inert type-5 generic objects (idempotent)
with open(os.path.join(proj, 'custom-sql', '008_decor_templates.sql'), 'w') as f:
    f.write('-- GENERATED by tools/find_decor_models.py: inert generic gameobject templates (910000+) for client models that had no usable stock template. Idempotent.\nUSE acore_world;\nDELETE FROM gameobject_template WHERE entry BETWEEN %d AND %d;\n' % (BASE, new[-1][0]))
    for i in range(0, len(new), 200):
        f.write('INSERT INTO gameobject_template (entry, type, displayId, name, IconName, castBarCaption, unk1, size, AIName, ScriptName, VerifiedBuild) VALUES\n')
        f.write(',\n'.join("(%d, 5, %d, '%s', '', '', '', 1, '', '', 12340)" % (e, dp, nm.replace("'", "''")) for e, dp, nm, m in new[i:i + 200]) + ';\n')
keep = [l for l in lines if not (l.split('\t')[12:13] == ['pass3'])]
with open(sheet, 'w') as f:
    f.write('\n'.join(keep) + '\n')
    for e, dp, nm, m in new: f.write('\t'.join(map(str, ('Y', 'Neutral', 'Unsorted', nm, e, dp, 5, 1, 1, m.split('\\')[-1], '', m, 'pass3'))) + '\n')
print('wrote custom-sql/008_decor_templates.sql and', len(new), 'sheet rows')
